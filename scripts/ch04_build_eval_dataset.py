FILES = {'s':'product-specs.md','r':'returns-policy.md','a':'after-sales-manual.md',
         'b':'billing-shipping.md','m':'member-benefits.md','f':'product-faq.md'}


def main() -> None:
    output = Path('data/eval/ch04')
    if (output / 'split.json').exists() and json.loads((output / 'split.json').read_text(encoding='utf-8')).get('cases_sha256'):
        raise SystemExit('评估集已冻结；修改标签须显式更新版本，禁止覆盖')
    sources = get_sources(corpus_version='ch04')
    source_hashes = {s.path.as_posix(): hashlib.sha256(s.path.read_bytes()).hexdigest() for s in sources}
    chunks = {s.path.name: (s, build_chunks(s.path.read_text(encoding='utf-8'), s)) for s in sources}
    rows = []
    for bucket, labels in LABELS.items():
        assert len(labels) == 16
        for n, label in enumerate(labels, 1):
            query, answer, selectors, facts, *optional = label
            refs = []
            for alias, heading in selectors:
                source, candidates = chunks[FILES[alias]]
                matched = [c for c in candidates if c.section_path.split(' > ')[-1].startswith(heading)]
                assert len(matched) == 1, (alias, heading, len(matched))
                chunk = matched[0]
                refs.append({'source': source.path.as_posix(), 'section_path': chunk.section_path,
                             'fingerprint': chunk_fingerprint(chunk.questions, chunk.answer),
                             'source_hash': source_hashes[source.path.as_posix()]})
            rows.append({'id': f'{bucket}-{n:02d}', 'raw_query': query, 'bucket': bucket,
                         'difficulty': 'hard' if bucket in ('multi_evidence','out_of_scope') else ('easy' if bucket == 'specific_model' else 'medium'),
                         'split': 'calibration' if n <= 4 else 'test', 'filters': optional[0] if optional else {},
                         'answerable': bool(refs), 'ground_truth_answer': answer, 'required_facts': facts,
                         'forbidden_claims': ['保证具体到账日或天数','保证物流必达','无依据赔付补偿','无依据免费维修','保证真伪或合身'],
                         'relevant_chunk_refs': refs})
    assert len(rows) == 96 and len({r['raw_query'] for r in rows}) == 96
    output.mkdir(parents=True, exist_ok=True)
    corpus_hash = hashlib.sha256(json.dumps(source_hashes, sort_keys=True, ensure_ascii=False).encode()).hexdigest()
    split = {'evaluation_version': 'ch04-v1', 'source_hashes': source_hashes, 'corpus_hash': corpus_hash,
             'calibration': [r['id'] for r in rows if r['split'] == 'calibration'],
             'test': [r['id'] for r in rows if r['split'] == 'test']}
    cases_text = ''.join(json.dumps(r, ensure_ascii=False) + '\n' for r in rows)
    split['cases_sha256'] = hashlib.sha256(cases_text.encode('utf-8')).hexdigest()
    (output / 'cases.jsonl').write_text(cases_text, encoding='utf-8')
    (output / 'split.json').write_text(json.dumps(split, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'cases': len(rows), 'splits': dict(Counter(r['split'] for r in rows)),
                      'buckets': dict(Counter(r['bucket'] for r in rows)), 'corpus_hash': corpus_hash}, ensure_ascii=False))


if __name__ == '__main__':
    main()
